#!/usr/bin/env python3
"""Schreibt looks/src/unicode_table.rs aus Pythons eigener Unicode-Datenbank.

looks.py zaehlt mit unicodedata, wie breit Text im Terminal ist. So nutzt die
Rust-Fassung dieselben Daten statt einer Crate mit anderem Unicode-Stand.

Aufruf: compare/gen_unicode_table.py looks/src/unicode_table.rs
"""

import sys
import unicodedata


def ranges(test):
    out, start = [], None
    for cp in range(0x110000):
        if test(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def zero(ch):
    return bool(unicodedata.combining(ch)) or unicodedata.category(ch) in ("Mn", "Me", "Cf")


def wide(ch):
    return unicodedata.east_asian_width(ch) in ("W", "F")


def table(name, items):
    lines = [f"static {name}: [(u32, u32); {len(items)}] = ["]
    lines += [f"    (0x{a:x}, 0x{b:x})," for a, b in items]
    lines.append("];")
    return "\n".join(lines)


text = f"""//! Generated by `compare/gen_unicode_table.py` from Unicode {unicodedata.unidata_version}.
//! Do not edit by hand.

fn contains(table: &[(u32, u32)], c: char) -> bool {{
    let c = u32::from(c);
    table.binary_search_by(|&(lo, hi)| {{
        if c < lo {{
            std::cmp::Ordering::Greater
        }} else if c > hi {{
            std::cmp::Ordering::Less
        }} else {{
            std::cmp::Ordering::Equal
        }}
    }}).is_ok()
}}

/// Combining characters and format characters take no cell.
pub fn is_zero_width(c: char) -> bool {{
    contains(&ZERO_WIDTH, c)
}}

/// East Asian wide and fullwidth characters take two cells.
pub fn is_wide(c: char) -> bool {{
    contains(&WIDE, c)
}}

{table("ZERO_WIDTH", ranges(zero))}

{table("WIDE", ranges(wide))}
"""
with open(sys.argv[1], "w") as f:
    f.write(text)
